USE B2BWholesaleDB;
GO
DROP TABLE IF EXISTS OrderDetail; DROP TABLE IF EXISTS [Order]; DROP TABLE IF EXISTS Users; DROP TABLE IF EXISTS Item; DROP TABLE IF EXISTS Agent;
GO
CREATE TABLE Item(ItemID INT IDENTITY(1,1) PRIMARY KEY, ItemName NVARCHAR(100) NOT NULL, Size NVARCHAR(50) NULL,
 Price DECIMAL(18,2) NOT NULL CHECK(Price>=0), StockQuantity INT NOT NULL DEFAULT 0 CHECK(StockQuantity>=0));
CREATE TABLE Agent(AgentID INT IDENTITY(1,1) PRIMARY KEY, AgentName NVARCHAR(100) NOT NULL, Address NVARCHAR(200) NULL, Phone VARCHAR(20) NULL);
CREATE TABLE [Order](OrderID INT IDENTITY(1,1) PRIMARY KEY, OrderDate DATETIME NOT NULL DEFAULT GETDATE(), AgentID INT NOT NULL,
 OrderStatus NVARCHAR(20) NOT NULL DEFAULT 'Pending' CHECK(OrderStatus IN ('Pending','Processing','Shipped','Delivered','Cancelled')),
 CONSTRAINT FK_Order_Agent FOREIGN KEY(AgentID) REFERENCES Agent(AgentID) ON UPDATE CASCADE);  -- NO ACTION on delete: keep order history
CREATE TABLE OrderDetail(ID INT IDENTITY(1,1) PRIMARY KEY, OrderID INT NOT NULL, ItemID INT NOT NULL,
 Quantity INT NOT NULL CHECK(Quantity>0), UnitAmount DECIMAL(18,2) NOT NULL CHECK(UnitAmount>=0),
 CONSTRAINT FK_OD_Order FOREIGN KEY(OrderID) REFERENCES [Order](OrderID) ON DELETE CASCADE ON UPDATE CASCADE,
 CONSTRAINT FK_OD_Item FOREIGN KEY(ItemID) REFERENCES Item(ItemID) ON UPDATE CASCADE,
 CONSTRAINT UQ_OD UNIQUE(OrderID,ItemID));
CREATE TABLE Users(UserID INT IDENTITY(1,1) PRIMARY KEY, UserName NVARCHAR(50) NOT NULL UNIQUE, Email NVARCHAR(100) NOT NULL UNIQUE,
 Password VARCHAR(64) NOT NULL, [Lock] BIT NOT NULL DEFAULT 0, FailedAttempts INT NOT NULL DEFAULT 0,
 Role NVARCHAR(20) NOT NULL CHECK(Role IN ('Admin','Agent')), AgentID INT NULL,
 CONSTRAINT FK_Users_Agent FOREIGN KEY(AgentID) REFERENCES Agent(AgentID) ON DELETE CASCADE ON UPDATE CASCADE);
GO
